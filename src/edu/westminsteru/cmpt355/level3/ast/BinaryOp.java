package edu.westminsteru.cmpt355.level3.ast;

/**
 * Enum of binary operations.
 */
public enum BinaryOp {
    ADD,      // +
    SUB,      // -
    MUL,      // *
    DIV,      // /
    MOD,      // %
    CONCAT,   // string concatenation
    // Comparison operators
    EQ,       // ==
    NE,       // !=
    LT,       // <
    LE,       // <=
    GT,       // >
    GE,       // >=
    // Logical operators
    AND,      // &&
    OR        // ||
}

